use crate::errors::InvoiceError;
use std::time::{SystemTime, UNIX_EPOCH};

const SECS_PER_DAY: i64 = 86_400;

#[tauri::command]
#[specta::specta]
fn current_date_dmy() -> Result<String, InvoiceError> {
    let secs = SystemTime::now()
    .duration_since(UNIX_EPOCH)
    .map_err(|e| InvoiceError::IoError(e.to_string()))?
    .as_secs();
    let secs = i64::try_from(secs).map_err(|e| InvoiceError::IoError(e.to_string()))?;
    let (year, month, day) = civil_from_days(secs.div_euclid(SECS_PER_DAY));
    Ok(format!("{day:02}/{month:02}/{year:04}"))
}

const fn civil_from_days(days: i64) -> (i64, i64, i64) {
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let year = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    (if month <= 2 { year + 1 } else { year }, month, day)
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let specta_builder =
    tauri_specta::Builder::<tauri::Wry>::new().commands(tauri_specta::collect_commands![
        current_date_dmy,
        db::save_invoice,
        db::save_and_generate_pdf,
        db::get_setting,
        db::set_setting,
        db::save_signature,
        db::get_signature_path,
        db::parts::add_part,
        db::parts::get_parts,
        db::parts::update_part,
        db::parts::delete_part,
        db::parts::save_part_image,
        pdf::generate_invoice_pdf
    ]);

    let result = tauri::Builder::default()
    .plugin(tauri_plugin_opener::init())
    .plugin(tauri_plugin_dialog::init())
    .invoke_handler(specta_builder.invoke_handler())
    .setup(move |app| {
        db::initialize_db(app.handle())?;
        #[cfg(all(debug_assertions, not(mobile)))]
        {
            let export = specta_builder.export(
                specta_typescript::Typescript::default().header(
                    "// Generated by tauri-specta. DO NOT EDIT.\n/* eslint-disable */\n",
                ),
                "../src/lib/bindings.ts",
            );
            if let Err(e) = export {
                eprintln!("Failed to export TypeScript bindings: {e}");
            }
        }
        Ok(())
    })
    .run(tauri::generate_context!());

    if let Err(e) = result {
        eprintln!("Error running tauri application: {e}");
    }
}
